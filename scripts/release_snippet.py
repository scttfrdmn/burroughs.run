"""Generate generated/release.md: the latest Burroughs release's own words, for the landing page.

1. Resolve the latest vX.Y.Z tag through the GitHub API (scripts/latest_tag.py),
   unless BURROUGHS_TAG is set.
2. Fetch CHANGELOG.md at that tag from raw.githubusercontent.com.
3. Extract that version's block (`## [X.Y.Z] - DATE`): its contract line, its
   lead paragraphs (everything before the **Known limits** paragraph), and the
   Known limits list.
4. Write them, verbatim apart from relative links made absolute at the tag, to
   generated/release.md, which docs/index.md includes.

The landing page must say that no public path can yet start a second
shared-memory thread (#1122). That is v0.11.0's first Known limit; when a
release lifts it, the limit leaves the list and this check fails on purpose,
so the landing page's hand-written prose gets re-read in the same change.
Set ALLOW_NO_1122=1 once that has happened.

Usage: python3 scripts/release_snippet.py [--check]
  --check   do not write; fail if generated/release.md differs from what would be written.
"""

import os
import re
import sys
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import latest_tag  # noqa: E402

REPO = "scttfrdmn/burroughs"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "generated", "release.md")


def fetch(tag):
    url = f"https://raw.githubusercontent.com/{REPO}/{tag}/CHANGELOG.md"
    with urllib.request.urlopen(url, timeout=30) as resp:
        return resp.read().decode("utf-8")


def block(changelog, version):
    head = re.compile(r"^## \[" + re.escape(version) + r"\] - (\d{4}-\d{2}-\d{2})\s*$", re.M)
    m = head.search(changelog)
    if not m:
        sys.exit(f"release_snippet: no '## [{version}] - DATE' heading in CHANGELOG.md")
    rest = changelog[m.end():]
    nxt = re.search(r"^## \[", rest, re.M)
    return m.group(1), rest[: nxt.start()] if nxt else rest


def paragraphs(text):
    """Split into blank-line-separated chunks, keeping each chunk's lines intact."""
    return [p.strip("\n") for p in re.split(r"\n\s*\n", text) if p.strip()]


def absolute_links(md, tag):
    def fix(m):
        target = m.group(2)
        if re.match(r"^(https?:|mailto:|#)", target):
            return m.group(0)
        return f"{m.group(1)}(https://github.com/{REPO}/blob/{tag}/{target.lstrip('./')})"

    return re.sub(r"(\[[^\]]*\])\(([^)\s]+)\)", fix, md)


def extract(text):
    # The lead stops at the first ### subsection.
    lead_text = re.split(r"^### ", text, maxsplit=1, flags=re.M)[0]
    contract, lead, limits_intro, limits = None, [], None, None
    chunks = paragraphs(lead_text)
    i = 0
    while i < len(chunks):
        c = chunks[i]
        if contract is None and re.match(r"^\*Implements contract", c):
            contract = c
        elif c.startswith("**Known limits"):
            # The intro line may carry the list directly beneath it.
            lines = c.split("\n")
            limits_intro = lines[0]
            items = "\n".join(lines[1:]).strip("\n")
            # Gather following list chunks (a list may be split by blank lines).
            j = i + 1
            while j < len(chunks) and re.match(r"^\s*[-*] ", chunks[j]):
                items += "\n" + chunks[j]
                j += 1
            limits = items
            return contract, lead, limits_intro, limits
        else:
            lead.append(c)
        i += 1
    sys.exit("release_snippet: no **Known limits** paragraph before the first ### subsection")


def render(tag, date, contract, lead, limits_intro, limits):
    src = f"https://github.com/{REPO}/blob/{tag}/CHANGELOG.md"
    out = [
        "<!-- Generated by scripts/release_snippet.py from CHANGELOG.md at "
        f"{tag}. Do not edit; re-run the script. -->",
        "",
        f"## The current release: `{tag}` ({date})",
        "",
        '<div class="bx-release" markdown>',
        "",
    ]
    if contract:
        out += [contract, ""]
    for p in lead:
        out += [p, ""]
    out += [limits_intro, "", limits, "", "</div>", ""]
    out += [
        f'<p class="bx-generated">Quoted from the <a href="{src}">{tag} block of the engine\'s CHANGELOG.md</a>, '
        "regenerated from the latest release tag on every build. References to sections \"below\" are to that "
        "CHANGELOG block.</p>",
        "",
    ]
    md = absolute_links("\n".join(out), tag)
    # The CHANGELOG is hard-wrapped, so a wrapped line can begin with an issue number ("#1121)."), which
    # Python-Markdown would read as a heading. Escape a line-leading '#' that is not a real heading.
    return re.sub(r"(?m)^(\s*)#(?=[^#\s])", r"\1\\#", md)


def main():
    check = "--check" in sys.argv[1:]
    tag = os.environ.get("BURROUGHS_TAG") or latest_tag.latest(REPO)
    date, text = block(fetch(tag), tag.lstrip("v"))
    contract, lead, limits_intro, limits = extract(text)
    if "#1122" not in limits and "/issues/1122" not in limits and not os.environ.get("ALLOW_NO_1122"):
        sys.exit(
            "release_snippet: the Known limits of " + tag + " no longer cite #1122 (no public path starts a "
            "second shared-memory thread). Re-read docs/index.md's prose, then set ALLOW_NO_1122=1."
        )
    md = render(tag, date, contract, lead, limits_intro, limits)
    if check:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != md:
            sys.exit(f"release_snippet: generated/release.md is stale against {tag}; re-run the script")
        print(f"release_snippet: generated/release.md is current for {tag}")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(md)
    print(f"release_snippet: wrote generated/release.md from {tag} ({date})")


if __name__ == "__main__":
    main()
